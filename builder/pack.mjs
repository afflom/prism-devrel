#!/usr/bin/env node
/**
 * Write builder/assets.mjs from builder/assets/, so the builder carries its
 * fixed files as one module that loads the same way in Node and in the
 * browser. `--check` fails when assets.mjs is not exactly what this writes.
 *
 *   assets/app/        files every generated app/ carries unchanged: the
 *                      prism.arch, prism.qual and prism.sec language packages,
 *                      the Foundation and Production modules, lean-toolchain
 *   assets/template/   the UOR-Foundation/template files a generated instance
 *                      rewrites (at the commit frame.lock pins)
 *   assets/lock-packages.toml
 *                      the [[package]] section `lexlean lock` writes for the
 *                      language packages above, captured in the pinned SDK
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const walk = (dir) =>
  readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? walk(path) : [path];
    });
const table = (root) => Object.fromEntries(walk(join(here, root)).map((p) => [relative(join(here, root), p).split('\\').join('/'), readFileSync(p, 'utf8')]));

export function render() {
  const lines = [
    '// @generated by builder/pack.mjs from builder/assets/. Do not edit.',
    `export const ASSETS = ${JSON.stringify(table('assets/app'), null, 1)};`,
    `export const TEMPLATE = ${JSON.stringify(table('assets/template'), null, 1)};`,
    `export const LOCK_PACKAGES = ${JSON.stringify(readFileSync(join(here, 'assets/lock-packages.toml'), 'utf8'))};`,
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(here, 'assets.mjs');
  const text = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {}
    if (current !== text) {
      console.error('builder/assets.mjs is stale: run node builder/pack.mjs');
      process.exit(1);
    }
  } else writeFileSync(out, text);
}
