#!/usr/bin/env node
/**
 * The documentation shell's check, one per register row, as builder/test.mjs:
 *   node devrel/test.mjs DR-30
 * It prints "<ID>: <n> assertions passed", which crates/devrel/tests/shell.rs
 * requires, so a case that asserts nothing fails.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SITE = JSON.parse(readFileSync(join(here, 'site.json'), 'utf8'));
let made = 0;
const ok = (cond, what) => {
  made++;
  if (!cond) throw new Error(`failed: ${what}`);
};

const LIVE = 'https://example.test/devrel/';
const page = (title, diataxis, journey, body = '', extra = '') => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${title} · Prism-DevRel</title><meta name="description" content="About ${title}.">${diataxis ? `<meta name="diataxis" content="${diataxis}">` : ''}${journey ? `<meta name="developer-journey" content="${journey}">` : ''}<link rel="alternate" type="text/markdown" href="index.md"><link rel="stylesheet" href="../own.css">${extra}</head><body class="foundation"><header class="top"><nav><a href="../stale/">Stale</a></nav></header><main id="main" class="wide"><p class="eyebrow">// generator words</p><h1>${title}</h1><p class="lead">About ${title}.</p>${body}<h2>First part</h2><h2>Second part</h2><p class="twin">Plain text: <a href="index.md">Markdown twin</a>.</p></main><footer class="foot"><p>Generated by the fixture.</p></footer><script type="module" src="../own.mjs"></script></body></html>
`;

const col = (id, group) => `<meta name="collection" content="${id}"><meta name="collection-group" content="${group}">`;

/** A site as the generators leave it: two catalog pages, a tutorial, an app page. */
function fixture(edit = () => {}) {
  const site = mkdtempSync(join(tmpdir(), 'devrel-shell-'));
  const put = (rel, text) => {
    mkdirSync(dirname(join(site, rel)), { recursive: true });
    writeFileSync(join(site, rel), text);
  };
  put('app.json', JSON.stringify({ live: LIVE }));
  put('index.html', '<!doctype html><html><head><title>App</title></head><body><header class="head"><div class="ident"><h1 id="name">App</h1><p id="lede" class="lede">An app.</p><nav class="head-nav" aria-label="Where to go">' + SITE.app.links.map((l) => `<a class="go-link" href="./${l.path}">${l.label}</a>`).join('') + '</nav></div><a id="open-spec" class="spec-link" href="#spec"><span>View spec</span></a></header><aside id="spec"></aside></body></html>');
  put('own.css', '');
  put('spec.html', '<section><h2>Spec</h2></section>');
  put('favicon.svg', '<svg xmlns="http://www.w3.org/2000/svg"/>');
  put('own.mjs', '');
  put('facets/own.css', '');
  put('facets/own.mjs', '');
  put('start/own.css', '');
  put('start/own.mjs', '');
  put('facets/index.html', page('Catalog', 'explanation', 'discover', '<p><a href="../start/#first-part">Tutorial, first part</a></p>'));
  put('facets/index.md', '# Catalog');
  put('facets/walk/index.html', page('Walkthrough', 'reference', 'build').replace(/\.\.\/own/g, '../../facets/own'));
  put('facets/walk/index.md', '# Walkthrough');
  put('start/index.html', page('First app', 'tutorial', 'learn'));
  put('examples/index.html', page('Examples', 'howToGuide', 'build', '', col('examples', 'Overview')));
  put('examples/index.md', '# Examples');
  put('examples/door/index.html', page('Door', 'howToGuide', 'build', '', col('examples', 'State machines')).replace(/\.\.\/own/g, '../../facets/own'));
  put('examples/door/index.md', '# Door');
  put('examples/gate/index.html', page('Gate', 'howToGuide', 'build', '', col('examples', 'Decision tables')).replace(/\.\.\/own/g, '../../facets/own'));
  put('examples/gate/index.md', '# Gate');
  put('case-studies/index.html', page('Case studies', 'explanation', 'evaluate', '', col('case-studies', 'Overview')));
  put('case-studies/index.md', '# Case studies');
  put('case-studies/demo/index.html', page('How Demo was modeled', 'explanation', 'evaluate', '', col('case-studies', 'Demo')).replace(/\.\.\/own/g, '../../facets/own'));
  put('case-studies/demo/index.md', '# Demo');
  put('case-studies/demo/try/index.html', page('Try Demo', 'tutorial', 'learn').replace(/\.\.\/own/g, '../../../facets/own').replace(/\.\.\/stale/g, '../../../stale'));
  put('case-studies/demo/try/index.md', '# Try Demo');
  put('llms.txt', `# X\n\n> y\n\nSubject: z.\n\n## Pages\n\n- [Walkthrough](${LIVE}facets/walk/index.md): w\n- [Catalog](${LIVE}facets/index.md): c\n\n## Data\n\n- [records.json](${LIVE}facets/records.json): data\n\n## More\n\n- [First app](start/index.md): t\n`);
  put('llms-full.txt', `---\ntitle: "Catalog"\nurl: ${LIVE}facets/\n---\n\n# Catalog\n`);
  put('feed.xml', `<?xml version="1.0"?>\n<rss version="2.0"><channel><title>t</title>\n<item><title>Catalog</title><link>${LIVE}facets/</link></item>\n</channel></rss>\n`);
  put('start/index.md', '# First app\n\nSee [the catalog](../facets/index.md) and [a part](#first-part).\n');
  edit(put, site);
  return site;
}

// Every documentation page the fixture writes.
const PAGES = 9;

const run = (site) => spawnSync(process.execPath, [join(here, 'shell.mjs'), site], { encoding: 'utf8' });

const cases = {
  'DR-30'() {
    const site = fixture();
    try {
      const r = run(site);
      ok(r.status === 0, `the shell accepts a well-formed site: ${r.stderr}`);
      const read = (rel) => readFileSync(join(site, rel), 'utf8');
      const walk = read('facets/walk/index.html');
      const start = read('start/index.html');
      for (const [rel, html] of [['facets/walk/index.html', walk], ['start/index.html', start], ['facets/index.html', read('facets/index.html')]]) {
        ok(html.includes('class="dc-header"') && html.includes('class="dc-tabs"') && html.includes('class="dc-foot"'), `${rel} has the one header, tabs and footer`);
        ok(!html.includes('class="top"') && !html.includes('../stale/'), `${rel} lost its generator's chrome`);
        ok(html.includes('docs/docs.css') && html.includes('own.css'), `${rel} links the shared stylesheet and keeps its own`);
        ok(html.includes('own.mjs'), `${rel} keeps its scripts`);
        ok((html.match(/class="dc-active" aria-current="true"/g) ?? []).length === 1, `${rel} marks exactly one tab`);
        ok(html.includes('Generated by the fixture.'), `${rel} keeps its provenance line`);
        ok(!html.includes('generator words') && !html.includes('class="twin"'), `${rel}: the eyebrow is the shell's and the twin is a chip`);
      }
      ok(walk.includes('// reference · Build') && walk.includes('>Reference</a>'), 'the eyebrow and crumbs name the type and stage');
      ok(walk.includes('<p>Build</p>') && walk.includes('aria-current="page"'), 'the side navigation groups the tab by stage and marks the page');
      ok(walk.includes('id="first-part"') && walk.includes('href="#second-part"'), 'every second-level heading gets an id and a place on the page list');
      ok(start.includes('// tutorial · Learn'), 'the tutorial is labeled as one');
      const hub = read('docs/index.html');
      ok(hub.includes('Your developer journey') && SITE.journey.stages.every((s) => hub.includes(`id="${s.id}"`)), 'the hub has a card per journey stage');
      ok(['Catalog', 'Walkthrough', 'First app'].every((t) => hub.includes(`>${t}</a>`)), 'the hub lists every page');
      ok(existsSync(join(site, 'docs/docs.css')) && existsSync(join(site, 'docs/fonts')), 'the shared stylesheet and its fonts are written');
      const llms = read('llms.txt');
      ok(llms.indexOf('## Tutorials') < llms.indexOf('## Reference') && llms.indexOf('## Reference') < llms.indexOf('## Explanation'), 'llms.txt lists pages by type, in Diátaxis order');
      ok(llms.includes(`(${LIVE}start/index.md)`) && !llms.includes('](start/index.md)'), 'llms.txt links every page absolutely');
      ok(llms.includes('## Data') && llms.includes('records.json') && !llms.includes('## Pages') && !llms.includes('## More'), 'llms.txt keeps data links and drops emptied sections');
      ok(llms.includes('Subject: z.'), 'llms.txt keeps the generators\' preamble');
      const full = read('llms-full.txt');
      ok((full.match(/^url: /gm) ?? []).length === PAGES && full.includes(`url: ${LIVE}start/`) && full.includes(`url: ${LIVE}examples/`), 'llms-full.txt gains every page it lacked, once');
      ok(full.includes(`](${LIVE}facets/index.md)`) && full.includes('](#first-part)'), 'llms-full.txt links absolutely and keeps fragments');
      const feed = read('feed.xml');
      ok((feed.match(/<item>/g) ?? []).length === PAGES && feed.includes('<category>tutorial</category>'), 'feed.xml gains every page it lacked, once');
      ok(read('sitemap.xml').includes(`<loc>${LIVE}facets/walk/</loc>`), 'sitemap.xml lists the pages');
      ok(run(site).status !== 0, 'a site already wrapped is refused rather than wrapped twice');
    } finally {
      rmSync(site, { recursive: true, force: true });
    }
    const refused = (what, edit, says) => {
      const s = fixture(edit);
      try {
        const r = run(s);
        ok(r.status !== 0 && r.stderr.includes(says), `${what} is refused naming ${says}: ${r.stderr}`);
      } finally {
        rmSync(s, { recursive: true, force: true });
      }
    };
    refused('an unknown Diátaxis type', (put) => put('facets/walk/index.html', page('Walkthrough', 'cookbook', 'build')), 'cookbook');
    refused('an unknown journey stage', (put) => put('facets/walk/index.html', page('Walkthrough', 'reference', 'adopt')), 'adopt');
    refused('a documentation page with neither', (put) => put('facets/walk/index.html', page('Walkthrough', '', '')), 'facets/walk/index.html');
    refused('a link to nothing', (put) => put('start/index.html', page('First app', 'tutorial', 'learn', '<a href="../facets/gone/">gone</a>')), '../facets/gone/');
    refused('a fragment that names no id', (put) => put('start/index.html', page('First app', 'tutorial', 'learn', '<a href="../facets/#nowhere">x</a>')), '#nowhere');
    refused('an app page without its ways on', (put) => put('index.html', '<!doctype html><html><head><title>App</title></head><body></body></html>'), 'app.json "links"');
    refused('an app page missing a way on', (put) => put('index.html', '<!doctype html><html><body><nav class="head-nav"><a href="./docs/">Docs</a></nav></body></html>'), 'devrel/site.json names');
  },
  'DR-31'() {
    const site = fixture();
    try {
      const r = run(site);
      ok(r.status === 0, `the shell accepts a site with collections: ${r.stderr}`);
      const read = (rel) => readFileSync(join(site, rel), 'utf8');
      const tabs = (html) => [...html.match(/<nav class="dc-tabs"[\s\S]*?<\/nav>/)[0].matchAll(/>([^<]+)<\/a>/g)].map((m) => m[1]);
      const side = (html) => [...html.match(/<nav class="dc-side"[\s\S]*?<\/nav>/)[0].matchAll(/<p>([^<]+)<\/p>|>([^<]+)<\/a>/g)].map((m) => (m[1] ? `#${m[1]}` : m[2]));
      const door = read('examples/door/index.html');
      const names = tabs(door);
      ok(names.indexOf('Explanation') < names.indexOf('Examples') && names.indexOf('Examples') < names.indexOf('Case studies'), `each collection has a tab after the Diátaxis tabs: ${names}`);
      ok(!names.includes('How-to guides'), 'a type whose pages all belong to collections has no tab of its own');
      ok(/class="dc-active" aria-current="true">Examples</.test(door), 'an example is in the Examples tab');
      ok(side(door).join('|') === '#Overview|Examples|#State machines|Door|#Decision tables|Gate', `the collection's side navigation is its landing page, then its groups in order: ${side(door)}`);
      ok(door.includes('// example · State machines'), 'the eyebrow names the collection and the group');
      ok(door.includes('>how-to guide</a>') && door.includes('>Build</a>') && door.includes('>example</a>'), 'the page keeps its Diátaxis type and journey stage as labels, beside its collection');
      ok(door.includes('<meta name="collection" content="examples">') && door.includes('<meta name="collection-group" content="State machines">'), 'the wrapped page still names its collection');
      ok(door.includes('<a href="../">Examples</a>'), 'the crumbs lead to the collection landing page');
      const demo = read('case-studies/demo/index.html');
      ok(/class="dc-active" aria-current="true">Case studies</.test(demo) && side(demo).join('|') === '#Overview|Case studies|#Demo|How Demo was modeled', `a case study is listed under its project: ${side(demo)}`);
      const start = read('start/index.html');
      ok(side(start).includes('Try Demo') && !side(start).includes('Door'), 'a page inside a collection directory that names no collection stays in its type\'s tab');
      ok(!side(read('facets/walk/index.html')).includes('Gate'), 'collection pages leave the Diátaxis tabs');
      const hub = read('docs/index.html');
      ok(hub.includes(`>${SITE.hub.ways}</h2>`) && ['First app', 'Try Demo', 'Examples', 'Case studies'].every((t) => hub.includes(`<strong>${t}</strong>`)), 'the hub offers every tutorial and every collection as a way to start');
      ok(hub.includes('id="examples"') && hub.includes('id="case-studies"') && hub.includes('>State machines</a>') && hub.includes('>Demo</a>'), 'the hub lists each collection by group');
      const map = hub.match(/<h2 id="map">[\s\S]*?<\/table>/)[0];
      ok(!map.includes('>Door</a>') && map.includes('>Walkthrough</a>'), 'the stage-by-type map lists documentation, not collections');
      const llms = read('llms.txt');
      ok(llms.indexOf('## Explanation') < llms.indexOf('## Examples') && llms.indexOf('## Examples') < llms.indexOf('## Case studies'), 'llms.txt lists each collection after the four types');
      ok(read('docs/index.md').includes('## Case studies'), 'the hub twin lists the collections');
    } finally {
      rmSync(site, { recursive: true, force: true });
    }
    const refused = (what, edit, says) => {
      const s = fixture(edit);
      try {
        const r = run(s);
        ok(r.status !== 0 && r.stderr.includes(says), `${what} is refused naming ${says}: ${r.stderr}`);
      } finally {
        rmSync(s, { recursive: true, force: true });
      }
    };
    refused('an unknown collection', (put) => put('examples/door/index.html', page('Door', 'howToGuide', 'build', '', col('cookbook', 'Doors'))), 'cookbook');
    refused('a collection without its group', (put) => put('examples/door/index.html', page('Door', 'howToGuide', 'build', '', '<meta name="collection" content="examples">')), 'collection-group');
    refused('a collection without a landing page', (put, site) => rmSync(join(site, 'case-studies/index.html')), 'no landing page');
  },
};

const id = process.argv[2];
if (!cases[id]) {
  console.error(`unknown case ${id}; one of ${Object.keys(cases).join(', ')}`);
  process.exit(64);
}
try {
  cases[id]();
  console.log(`${id}: ${made} assertions passed`);
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
